const now = new Date('2026-09-01T14:32:00');
const iso = (d: Date) => d.toISOString();

function daysAgo(n: number): string {
  const d = new Date(now);
  d.setDate(d.getDate() - n);
  return iso(d);
}

function monthsAgo(n: number): string {
  const d = new Date(now);
  d.setMonth(d.getMonth() - n);
  return iso(d);
}

function makeAISteps(overrides?: Partial<Record<number, AIStep['status']>>): AIStep[] {
  const steps = [
    { id: 1, title: 'Verify Purchase', description: 'Invoice validation and retailer confirmation' },
    { id: 2, title: 'Check Warranty Eligibility', description: 'Warranty period and coverage verification' },
    { id: 3, title: 'Analyze Reported Fault', description: 'Diagnostic code analysis and fault classification' },
    { id: 4, title: 'Analyze Uploaded Evidence', description: 'Photo, video, and document evidence review' },
    { id: 5, title: 'Compare Historical Claims', description: 'Similar claims pattern matching across database' },
    { id: 6, title: 'Detect Fraud Indicators', description: 'Suspicious pattern and anomaly detection' },
    { id: 7, title: 'Check Batch Failure Patterns', description: 'Product batch and manufacturing defect analysis' },
    { id: 8, title: 'Generate Recommended Action', description: 'AI decision synthesis and recommendation' },
  ];
  return steps.map((s) => ({
    ...s,
    status: overrides?.[s.id] ?? 'completed',
    detail: getStepDetail(s.id),
    timestamp: `14:32:${String(10 + s.id * 2).padStart(2, '0')}`,
  }));
}

function getStepDetail(id: number): string {
  const details: Record<number, string> = {
    1: 'Invoice verified against retailer database. Purchase confirmed.',
    2: 'Warranty active. Coverage applies to reported fault type.',
    3: 'Fault classified as mechanical component failure.',
    4: 'Evidence reviewed. Visual confirmation of defect.',
    5: 'Similar claims found in historical database.',
    6: 'No fraud indicators detected.',
    7: 'Batch analysis complete. No abnormal patterns.',
    8: 'Recommendation generated based on all evidence.',
  };
  return details[id] ?? '';
}

